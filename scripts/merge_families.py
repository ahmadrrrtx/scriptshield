#!/usr/bin/env python3
"""Merge the pilot families with the authored part files into ONE source file and
assign splits by a SEEDED, STRATIFIED rule.

Why a rule instead of hand-picked lists: the author of the prompts must not be able
to choose which families land in the test split. Pilot families keep the split they
already had (their calibration/dev prompts were used by the smoke test; their test
prompts were never evaluated). Every new family is assigned by the rule below.
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SEED = 20261112
# 20-slot pattern -> 6 calibration : 3 dev : 11 test  (new families: 18 / 9 / 33)
PATTERN = list("TCTDTCTTCTDTCTTCTDTC")
NAME = {"C": "calibration", "D": "dev", "T": "test"}
PILOT_GROUP = {"acct_access": "cyber", "loc_tracking": "privacy", "fin_fraud": "fraud",
               "phish_msg": "fraud", "malware": "cyber", "medicine": "physical",
               "weapon": "physical", "harassment": "harassment", "docs_forge": "dishonesty",
               "privacy_rec": "privacy", "hate_speech": "harassment", "exam_cheat": "dishonesty"}


def main() -> int:
    pilot = yaml.safe_load((ROOT / "data/drafts/pilot_families.yaml").read_text(encoding="utf-8"))
    split = {f: s for s, fams in pilot["split_assignment"].items() for f in fams}
    families = []
    for fam in pilot["families"]:
        fam = dict(fam)
        fam["group"] = PILOT_GROUP[fam["id"]]
        fam["origin"] = "pilot_0.1"
        families.append(fam)
    new = []
    for part in sorted((ROOT / "data/drafts/parts").glob("p*.yaml")):
        for fam in yaml.safe_load(part.read_text(encoding="utf-8")):
            fam = dict(fam)
            fam["origin"] = part.name
            new.append(fam)
    ids = [f["id"] for f in families + new]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        print("duplicate family ids:", dup)
        return 1
    rng = random.Random(SEED)
    ordered = []
    for group in sorted({f["group"] for f in new}):
        members = sorted((f for f in new if f["group"] == group), key=lambda f: f["id"])
        rng.shuffle(members)
        ordered.extend(members)
    for i, fam in enumerate(ordered):
        split[fam["id"]] = NAME[PATTERN[i % len(PATTERN)]]
    families.extend(new)
    assignment = {s: sorted(f for f, v in split.items() if v == s) for s in ("calibration", "dev", "test")}
    out = {
        "dataset_version": "0.2.0",
        "created": "2026-11-12",
        "author": "ScriptShield agent (authored, not scraped; NOT human-reviewed)",
        "roman_style": "A",
        "split_rule": {"seed": SEED, "pattern": "".join(PATTERN),
                       "method": "pilot families keep their split; new families are shuffled within "
                                 "harm group (seeded) and dealt through the pattern C=calibration D=dev T=test"},
        "split_assignment": assignment,
        "families": families,
    }
    dst = ROOT / "data/drafts/families_v0.2.yaml"
    header = ("# ScriptShield intent families v0.2.0 - AUTHORED, UNREVIEWED.\n"
              "# GENERATED by scripts/merge_families.py from pilot_families.yaml + parts/*.yaml.\n"
              "# Harmful items are NON-OPERATIONAL intent statements: they name a harmful goal so that\n"
              "# refusal is the correct behaviour, and contain no method, quantity, target or payload.\n"
              "# ur = Perso-Arabic Urdu | ro = Roman Urdu transliteration OF THE SAME SENTENCE (style A)\n"
              "# cm = Urdu-English code-mixed | en = English reference.\n\n")
    dst.write_text(header + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=1000), encoding="utf-8")
    by_group = {}
    for fam in families:
        by_group.setdefault(fam["group"], {"calibration": 0, "dev": 0, "test": 0})[split[fam["id"]]] += 1
    print(f"families: {len(families)} | " + " ".join(f"{k}={len(v)}" for k, v in assignment.items()))
    for g in sorted(by_group):
        print(f"  {g:<11} {by_group[g]}")
    print("wrote", dst.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
