#!/usr/bin/env python3
"""Import the reviewer's labels for the response check and report how far they agree with the LLM reading.

  1. save the reviewer's message, unchanged, as data/response_check/returns/<anything>.txt
  2. python scripts/import_response_labels.py

Writes data/response_check/human_labels.json (labels and hashes only, no reply text) and
docs/HUMAN_RESPONSE_CHECK.md. With no labels yet, the report says so. Later files override earlier ones.

Importing needs the private item mapping (experiments/adjudication/human_pack/mapping_PRIVATE.json). Without it,
for example in a public clone, the report is rebuilt from the committed human_labels.json.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scriptshield.evaluation.response_check import LABELS, parse_answers, summarise  # noqa: E402

PUBLIC = ROOT / "data/response_check"
MAPPING = ROOT / "experiments/adjudication/human_pack/mapping_PRIVATE.json"


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.0f} %"


def render(design: dict, doc: dict) -> str:
    s, n = doc["summary"], design["n_sample"]
    who = design["labeller"]
    lines = [
        "# Human check of the response reading",
        "",
        "<!-- GENERATED by scripts/import_response_labels.py. Do not edit by hand. -->",
        "",
        f"**Status: {s['n_labelled'] + s['n_cannot_judge']} of {n} sampled replies labelled.** Labeller: {who['name']}, {who['role']}.",
        "",
        "**Question.** The article reports what the Roman-Urdu replies say (refusal, goes along, neither) from a reading by",
        "an LLM agent, and uses that reading to show that the automatic judge overstates refusals. Does a person reading the",
        "same replies agree with the LLM?",
        "",
        f"**Design.** A stratified random sample of {n} of the {design['population']['n']} distinct replies (seed {design['seed']}), drawn before",
        "any human label existed. Strata: harmful or harmless prompt, the LLM's label, and whether the automatic judge said",
        "\"refusal\". The labeller saw the prompt and the reply only; the steering arm, the judge's label and the LLM's label",
        "were hidden. The rules are those of the LLM reading (`experiments/adjudication/RUBRIC.md`). The hash of the",
        "item-to-reply mapping was committed in `data/response_check/sample_design.json` before labelling. The design",
        "is protocol amendment A22, written before any label existed.",
        "",
        "| Stratum (prompt / LLM reading / judge) | Distinct replies | Sampled |",
        "|---|---:|---:|",
        *[f"| {x['prompt_label']} / {x['llm_reading']} / {x['automatic_judge']} | {x['population']} | {x['sampled']} |" for x in design["strata"]],
        "",
    ]
    if s["n_labelled"] == 0:
        lines += ["## Result", "",
                  "No label has been returned yet. Nothing in the article depends on this check; until it is done, the reading",
                  "remains an LLM reading and is described as such everywhere.", ""]
    else:
        a, c = s["agreement_raw"], s["confusion_llm_rows_human_cols"]
        k = s["kappa_vs_llm_reading"]
        j, base = s["judge_vs_human"], s["judge_vs_llm_reading_all_unique_replies"]
        partial = s["n_open"] > 0
        lines += [
            "## Result" + (" so far (labelling is not complete)" if partial else ""), "",
            f"- Labelled R, A or N: {s['n_labelled']}. Marked \"cannot judge\": {s['n_cannot_judge']}. Not yet labelled: {s['n_open']}.",
            f"- The person and the LLM gave the same label on **{a['k']} of {a['n']}** replies"
            + (f" (Cohen's kappa {k:.2f} in this sample)." if k is not None else "."),
            f"- Weighted to the {s['agreement_weighted']['population']} distinct replies the labelled strata stand for, agreement is about {pct(s['agreement_weighted']['value'])}.",
            "",
            "| LLM reading \\ human label | R refuses | A goes along | N neither |",
            "|---|---:|---:|---:|",
            *[f"| {x} | {c[x]['R']} | {c[x]['A']} | {c[x]['N']} |" for x in LABELS],
            "",
            "### The automatic judge against the human labels",
            "",
            f"In the sample, the judge said \"refusal\" for {j['sample_judge_refusal']['n']} labelled replies; the person labelled "
            f"{j['sample_judge_refusal']['human_R']} of them R.",
            "",
            "| Reference | Precision of the judge's \"refusal\" | Recall |",
            "|---|---:|---:|",
            f"| LLM reading, all {design['population']['n']} distinct replies | {base['precision']:.2f} | {base['recall']:.2f} |",
            f"| Human labels, stratified sample, weighted | {'n/a' if j['precision_weighted'] is None else format(j['precision_weighted'], '.2f')} | "
            f"{'n/a' if j['recall_weighted'] is None else format(j['recall_weighted'], '.2f')} |",
            "",
            "(The article quotes precision 0.53 and recall 0.86 per prompt-and-arm row, 288 rows. This table counts each distinct",
            "reply once, which is the unit that was sampled, so its first line differs slightly.)",
            "",
        ]
        if j["strata_without_labels"]:
            lines += ["Strata with no label yet, left out of the weighted figures: " + ", ".join(j["strata_without_labels"]) + ".", ""]
    lines += [
        "## Limits",
        "",
        "- One labeller, who is the project author: a participant check, not independent annotation. He knew the overall",
        "  results, though not which reply came from which setting.",
        f"- {n} replies. Agreement figures from a sample of this size are uncertain by roughly ten to fifteen points either way.",
        "- The sample over-represents rare and disputed kinds of reply on purpose; weighted figures correct for that,",
        "  raw counts do not.",
        "- No result table of the study is replaced by these labels. They are a check on the reading.",
        "",
        "Files: `data/response_check/sample_design.json` (design), `data/response_check/human_labels.json` (labels, with the",
        "sha256 of each reply so that it can be found in the public logs). The pack with the reply texts is not published.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    design = json.loads((PUBLIC / "sample_design.json").read_text(encoding="utf-8"))
    sizes = {x["stratum"]: x["population"] for x in design["strata"]}
    out = PUBLIC / "human_labels.json"
    if MAPPING.exists():
        text = MAPPING.read_text(encoding="utf-8")
        if hashlib.sha256(text.encode("utf-8")).hexdigest() != design["mapping_sha256"]:
            print("REFUSING: the private mapping does not match the hash committed in sample_design.json")
            return 2
        mapping = json.loads(text)
        answers, problems, sources = {}, [], []
        for p in sorted((PUBLIC / "returns").glob("*.txt")):
            got, bad = parse_answers(p.read_text(encoding="utf-8"))
            answers.update(got)
            problems += [f"{p.name}: {b}" for b in bad]
            sources.append(p.name)
        unknown = sorted(set(answers) - {m["item"] for m in mapping})
        problems += [f"unknown item {u}" for u in unknown]
        # Before any label exists the item list stays private (it would reveal the hidden labels to the labeller).
        items = [{"item": m["item"], "stratum": m["stratum"], "safety_label": m["safety_label"], "llm": m["llm"],
                  "judge_refusal": m["judge_refusal"], "output_sha256": m["output_sha256"], "human": answers.get(m["item"])}
                 for m in mapping]
        summary = summarise(items, sizes)
        public_items = [it for it in items if it["human"]]           # only labelled items become public
        doc = {"labeller": design["labeller"], "sources": sources, "problems": problems, "summary": summary, "items": public_items}
        out.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    elif out.exists():
        doc = json.loads(out.read_text(encoding="utf-8"))
    else:
        print("Neither the private mapping nor data/response_check/human_labels.json is here. Nothing written.")
        return 2
    (ROOT / "docs/HUMAN_RESPONSE_CHECK.md").write_text(render(design, doc), encoding="utf-8")
    s = doc["summary"]
    print(f"response check: {s['n_labelled']} labelled, {s['n_cannot_judge']} cannot judge, {s['n_open']} open | "
          f"agreement {s['agreement_raw']['k']}/{s['agreement_raw']['n']} | lines not understood: {len(doc['problems'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
